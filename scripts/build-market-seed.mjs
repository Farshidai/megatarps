// Builds supabase/seed-market-ttw-2026-10-25.sql from supabase/pricing/tarps-wholesaler.csv
// (The Tarps Wholesaler = Xpose's own online store, checked 2026-10-25).
// Every row (single, half_pallet, full_pallet) becomes a market_observations row keyed by
// the Xpose SKU (STH-2030, BTH-3040, MTGB-1530, ...). The admin "Reprice from market" action
// reads the latest full_pallet (else half_pallet) observation per SKU.
// Usage: node scripts/build-market-seed.mjs [csv] [out.sql]
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCE = 'The Tarps Wholesaler (Xpose store)'
const csvPath = process.argv[2] ?? 'supabase/pricing/tarps-wholesaler.csv'
const outPath = process.argv[3] ?? 'supabase/seed-market-ttw-2026-10-25.sql'

const lines = readFileSync(csvPath, 'utf8').split(/\r?\n/).filter((l) => l.trim())
const header = lines.shift().split(',')
const idx = Object.fromEntries(header.map((h, i) => [h.trim(), i]))
for (const need of ['sku', 'kind', 'units', 'price_cents', 'store_sku', 'source_url', 'checked_at']) {
  if (!(need in idx)) throw new Error(`${csvPath}: missing column ${need}`)
}

const q = (s) => (s == null || s === '' ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`)
const KINDS = new Set(['single', 'case', 'half_pallet', 'full_pallet', 'pack'])
const seen = new Map()
let skipped = 0
for (const line of lines) {
  const c = line.split(',')
  const sku = c[idx.sku].trim().toUpperCase()
  const kind = c[idx.kind].trim()
  const units = Number(c[idx.units])
  const price = Number(c[idx.price_cents])
  const date = c[idx.checked_at].trim()
  if (!sku || !KINDS.has(kind) || !Number.isInteger(units) || units < 1 || !Number.isInteger(price) || price < 1 || !/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    skipped++
    continue
  }
  // UNIQUE (sku, source, kind, units, checked_at): keep the lowest price if the store lists a duplicate
  const key = `${sku}|${kind}|${units}|${date}`
  const prev = seen.get(key)
  if (prev && prev.price <= price) continue
  seen.set(key, { sku, kind, units, price, date, url: c[idx.source_url].trim(), note: `store SKU ${c[idx.store_sku].trim()}` })
}

const rows = [...seen.values()].sort((a, b) => a.sku.localeCompare(b.sku) || a.units - b.units)
const pallets = rows.filter((r) => r.kind !== 'single').length
let sql = `-- GENERATED by scripts/build-market-seed.mjs from ${csvPath} — do not edit by hand.
-- The Tarps Wholesaler (Xpose's own online store) prices, checked ${rows[0]?.date ?? ''}.
-- ${rows.length} observations (${pallets} half/full pallet, ${rows.length - pallets} single). Admin-only reference data
-- (market_observations has no public grants). Used by /admin/products "Reprice from market".
-- Run after migration 0010_market_observations.sql. Safe to re-run (upsert).
INSERT INTO market_observations (sku, source, kind, units, price_cents, url, note, checked_at) VALUES
`
sql += rows
  .map((r) => `  (${q(r.sku)}, ${q(SOURCE)}, ${q(r.kind)}, ${r.units}, ${r.price}, ${q(r.url)}, ${q(r.note)}, ${q(r.date)})`)
  .join(',\n')
sql += `
ON CONFLICT (sku, source, kind, units, checked_at) DO UPDATE
  SET price_cents = EXCLUDED.price_cents, url = EXCLUDED.url, note = EXCLUDED.note;
`
writeFileSync(outPath, sql)
console.log(`${outPath}: ${rows.length} observations (${pallets} pallet), ${skipped} skipped`)
